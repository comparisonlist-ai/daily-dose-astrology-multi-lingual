function showRashi(rashi, scroll = true) {
  const data = rashifal[rashi];

  if (!data) {
    return;
  }

  currentRashi = rashi;

  document.querySelectorAll(".rashi-card").forEach(card => {
    card.classList.remove("selected");
  });

  const selectedCard = document.querySelector(
    '.rashi-card[data-rashi="' + rashi + '"]'
  );

  if (selectedCard) {
    selectedCard.classList.add("selected");
  }

  const isEnglish = currentLanguage === "en";
  const isOdia = currentLanguage === "or";

  const name =
    isEnglish
      ? data.nameEn
      : isOdia
      ? data.nameOr
      : data.nameHi;

  document.getElementById("rashiTitle").textContent =
    isEnglish
      ? "✨ " + name + " Today's Horoscope"
      : isOdia
      ? "✨ " + name + " ଆଜିର ରାଶିଫଳ"
      : "✨ " + name + " राशि का आज का राशिफल";

  document.getElementById("love").textContent =
    isEnglish ? data.love.en : isOdia ? data.love.or : data.love.hi;

  document.getElementById("career").textContent =
    isEnglish ? data.career.en : isOdia ? data.career.or : data.career.hi;

  document.getElementById("money").textContent =
    isEnglish ? data.money.en : isOdia ? data.money.or : data.money.hi;

  document.getElementById("health").textContent =
    isEnglish ? data.health.en : isOdia ? data.health.or : data.health.hi;

  document.getElementById("luckyNumber").textContent =
    data.luckyNumber;

  document.getElementById("luckyColor").textContent =
    isEnglish
      ? data.luckyColor.en
      : isOdia
      ? data.luckyColor.or
      : data.luckyColor.hi;

  document.getElementById("advice").textContent =
    isEnglish ? data.advice.en : isOdia ? data.advice.or : data.advice.hi;

  const prediction = document.getElementById("prediction");

  prediction.classList.remove("hidden");

  if (scroll) {
    prediction.scrollIntoView({
      behavior: "smooth",
      block: "start"
    });
  }
}

