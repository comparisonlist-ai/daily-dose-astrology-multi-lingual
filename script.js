let currentLanguage = localStorage.getItem("language") || "hi";

function setLanguage(language) {
  currentLanguage = language;
  localStorage.setItem("language", language);

  updateInterface();
  
  const selectedRashi = document.querySelector(".rashi-card.selected");

  if (selectedRashi) {
    const rashi = selectedRashi.getAttribute("data-rashi");
    showRashi(rashi, false);
  }
}

function updateInterface() {
  const isEnglish = currentLanguage === "en";

  document.documentElement.lang = isEnglish ? "en" : "hi";

  document.title = isEnglish
    ? "Daily Dose Astrology | Today's Horoscope"
    : "Daily Dose Astrology | आज का राशिफल";

  document.querySelector('meta[name="description"]').setAttribute(
    "content",
    isEnglish
      ? "Daily Dose Astrology brings you today's horoscope, love, career, money, health, lucky number, lucky color and daily advice."
      : "Daily Dose Astrology पर जानें आज का राशिफल, प्रेम, करियर, धन, स्वास्थ्य, शुभ अंक, शुभ रंग और आज की सलाह।"
  );

  document.querySelector(".header p").textContent =
    isEnglish ? "Today's Horoscope" : "आज का राशिफल";

  document.getElementById("todayDate").textContent =
    new Date().toLocaleDateString(
      isEnglish ? "en-IN" : "hi-IN",
      {
        weekday: "long",
        year: "numeric",
        month: "long",
        day: "numeric"
      }
    );

  document.querySelectorAll(".rashi-card").forEach(card => {
    const rashi = card.getAttribute("data-rashi");
    const data = rashifal[rashi];

    card.querySelector("strong").textContent =
      isEnglish ? data.nameEn : data.nameHi;
  });

  document.querySelectorAll(".prediction-item h3")[0].textContent =
    isEnglish ? "❤️ Love" : "❤️ प्रेम";

  document.querySelectorAll(".prediction-item h3")[1].textContent =
    isEnglish ? "💼 Career" : "💼 करियर";

  document.querySelectorAll(".prediction-item h3")[2].textContent =
    isEnglish ? "💰 Money" : "💰 धन";

  document.querySelectorAll(".prediction-item h3")[3].textContent =
    isEnglish ? "❤️‍🩹 Health" : "❤️‍🩹 स्वास्थ्य";

  document.querySelectorAll(".prediction-item h3")[4].textContent =
    isEnglish ? "🔢 Lucky Number" : "🔢 शुभ अंक";

  document.querySelectorAll(".prediction-item h3")[5].textContent =
    isEnglish ? "🎨 Lucky Color" : "🎨 शुभ रंग";

  document.querySelectorAll(".prediction-item h3")[6].textContent =
    isEnglish ? "🙏 Today's Advice" : "🙏 आज की सलाह";

  document.querySelector("footer p").textContent =
    isEnglish
      ? "© 2026 Daily Dose Astrology"
      : "© 2026 Daily Dose Astrology";
}

function showRashi(rashi, scroll = true) {
  const data = rashifal[rashi];

  if (!data) {
    return;
  }

  const isEnglish = currentLanguage === "en";
  const name = isEnglish ? data.nameEn : data.nameHi;

  document.getElementById("rashiTitle").textContent =
    "✨ " +
    name +
    (isEnglish
      ? " Today's Horoscope"
      : " राशि का आज का राशिफल");

  document.getElementById("love").textContent =
    isEnglish ? data.love.en : data.love.hi;

  document.getElementById("career").textContent =
    isEnglish ? data.career.en : data.career.hi;

  document.getElementById("money").textContent =
    isEnglish ? data.money.en : data.money.hi;

  document.getElementById("health").textContent =
    isEnglish ? data.health.en : data.health.hi;

  document.getElementById("luckyNumber").textContent =
    data.luckyNumber;

  document.getElementById("luckyColor").textContent =
    isEnglish ? data.luckyColor.en : data.luckyColor.hi;

  document.getElementById("advice").textContent =
    isEnglish ? data.advice.en : data.advice.hi;

  const prediction = document.getElementById("prediction");

  prediction.classList.remove("hidden");

  if (scroll) {
    prediction.scrollIntoView({
      behavior: "smooth",
      block: "start"
    });
  }
}

function showTodayDate() {
  updateInterface();
}

